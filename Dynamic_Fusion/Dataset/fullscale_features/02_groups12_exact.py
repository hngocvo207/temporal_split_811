"""
02_groups12_exact.py
====================
Groups 1 (12 basic statistical) + 2 (6 temporal frequency) for ALL 2,973,489
nodes -- EXACT, not approximated.

Why these two groups are cheap while group 3 is not: both read only the SEED's
own incident edges. In a depth-2 BFS ball every 1-hop neighbour of the seed is
present, so `sub.out_edges(seed)` / `sub.in_edges(seed)` inside
select_add_features.py are exactly the seed's edges in the full graph. Building
the ball at all is therefore pure overhead for groups 1+2, and the whole thing
collapses to segmented reductions over the edge list.

Reproduces select_add_features.py semantics exactly, including:
  * parallel edges counted individually (MultiDiGraph -> len(out_txs))
  * self-loops contributing to BOTH out_txs and in_txs
  * min()/max() with default=0.0 on empty
  * lifetime_days = timedelta.days  (floor of whole days)
  * active_days   = number of distinct UTC calendar dates
  * ref = max incident timestamp; windows are ref-30d / ref-180d
  * the +1e-9 guards in direction_ratio and the short/long ratios

Usage: python3 02_groups12_exact.py [--pre-cutoff T]

NOTE -- transductive-timeline tradeoff (symmetric to mg_build_adjacency.py's
adj_inference vs adj_train split): the production artifact actually consumed
by train1.py/eval_full_test.py (features_output_all23_MG_fullscale.csv, via
08_assemble_csv.py) was generated by running this script WITHOUT
--pre-cutoff, i.e. tag="full" -> groups12_full.npz. No "precut<T_cutoff>"
variant has been produced. That means every account's group-1/2 feature
values (degree, amounts, active_days, lifetime_days, ...) reflect the FULL
edge timeline, including edges after T_cutoff -- for a 'train' account this
mostly doesn't matter for its OWN direct edges (train accounts have none
past T_cutoff by construction), but any feature that depends on graph-wide
structure (group 3 centrality, computed downstream from this same
full-timeline edge set) can still be shaped by post-cutoff activity
elsewhere in the network. Passing --pre-cutoff <T_cutoff> here (and to the
group-3 centrality step) would produce a strictly train-only-timeline
alternative for comparison; this has not been run (~22h on the full graph
per fullscale_feature_extraction_report.md's group-3 timing) -- see
dynamic_fusion_leakage_audit/pipeline_review_vs_code_check.md §D/§H.
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
ARR = HERE / "arrays"
DAY = 86400


def seg_max(idx, vals, n):
    """max of vals per idx, 0.0 where a group is empty (matches max(..., default=0.0))."""
    out = np.zeros(n, dtype=vals.dtype)
    np.maximum.at(out, idx, vals)
    return out


def seg_min(idx, vals, n, has_any):
    """min of vals per idx, 0.0 where empty (matches min(..., default=0.0))."""
    out = np.full(n, np.inf, dtype=np.float64)
    np.minimum.at(out, idx, vals)
    out[~has_any] = 0.0
    return out


def count_ge_threshold(node_of_edge, ts, thr_per_node, n, deg):
    """
    For every node i: how many of its edges have ts >= thr_per_node[i].

    Sorting edges by (node, ts) makes key = node<<32 | ts globally monotonic, so
    a single vectorised searchsorted answers all N nodes at once -- no per-node
    Python loop, no per-node slicing.
    """
    key = (node_of_edge.astype(np.int64) << 32) | ts.astype(np.int64)
    key.sort()
    end = np.cumsum(deg)                       # exclusive end offset per node
    probe = (np.arange(n, dtype=np.int64) << 32) | np.maximum(thr_per_node, 0).astype(np.int64)
    pos = np.searchsorted(key, probe, side="left")
    return (end - pos).astype(np.int64)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pre-cutoff", type=float, default=None,
                    help="If set, keep only edges with timestamp <= T (e.g. the split's "
                         "T_cutoff), i.e. the adj_train.npz view instead of the full graph.")
    ap.add_argument("--short-window", type=int, default=30)
    ap.add_argument("--long-window", type=int, default=180)
    ap.add_argument("--out", default=None)
    args = ap.parse_args()

    t0 = time.time()
    e = np.load(ARR / "edges.npz")
    src, dst, ts, val = e["src"], e["dst"], e["ts"], e["val"]
    n = len(np.load(ARR / "nodes.npy", allow_pickle=True))
    print(f"[✓] {n:,} nodes / {len(src):,} edges loaded ({time.time()-t0:.0f}s)", flush=True)

    tag = "full"
    if args.pre_cutoff is not None:
        keep = ts <= np.int64(args.pre_cutoff)
        src, dst, ts, val = src[keep], dst[keep], ts[keep], val[keep]
        tag = f"precut{int(args.pre_cutoff)}"
        print(f"[✓] pre-cutoff filter: {keep.sum():,}/{len(keep):,} edges kept "
              f"({100*keep.mean():.2f}%)", flush=True)

    out_path = Path(args.out) if args.out else HERE / f"groups12_{tag}.npz"
    SW, LW = args.short_window, args.long_window

    # ── degrees (parallel edges counted individually, as in the original) ─────
    t = time.time()
    out_deg = np.bincount(src, minlength=n).astype(np.int64)
    in_deg = np.bincount(dst, minlength=n).astype(np.int64)
    has_out, has_in = out_deg > 0, in_deg > 0
    incident = out_deg + in_deg                      # self-loop counted twice, as original
    print(f"[✓] degrees ({time.time()-t:.0f}s)", flush=True)

    # ── amount aggregates ────────────────────────────────────────────────────
    t = time.time()
    sum_out = np.bincount(src, weights=val, minlength=n)
    sum_in = np.bincount(dst, weights=val, minlength=n)
    max_out = seg_max(src, val, n)
    max_in = seg_max(dst, val, n)
    min_out = seg_min(src, val, n, has_out)
    min_in = seg_min(dst, val, n, has_in)
    avg_out = np.divide(sum_out, out_deg, out=np.zeros(n), where=has_out)
    avg_in = np.divide(sum_in, in_deg, out=np.zeros(n), where=has_in)
    balance = sum_in - sum_out
    print(f"[✓] amount aggregates ({time.time()-t:.0f}s)", flush=True)

    # ── incident timestamp range -> lifetime_days ────────────────────────────
    t = time.time()
    NEG = np.int64(-1)
    mx = np.full(n, NEG, dtype=np.int64)
    np.maximum.at(mx, src, ts)
    np.maximum.at(mx, dst, ts)
    mn = np.full(n, np.iinfo(np.int64).max, dtype=np.int64)
    np.minimum.at(mn, src, ts)
    np.minimum.at(mn, dst, ts)
    has_ts = incident > 0
    # timedelta.days == floor(seconds / 86400); original yields 0 unless >=2 timestamps
    lifetime_days = np.where(incident >= 2, (mx - mn) // DAY, 0)
    lifetime_days = np.where(has_ts, lifetime_days, 0).astype(np.int64)
    print(f"[✓] lifetime_days ({time.time()-t:.0f}s)", flush=True)

    # ── active_days = distinct UTC calendar dates over incident edges ────────
    t = time.time()
    day = (ts // DAY).astype(np.int64)
    d0 = day.min()
    dspan = int(day.max() - d0) + 1
    shift = int(np.ceil(np.log2(dspan)))             # bits needed for the day field
    pair = np.concatenate([
        (src.astype(np.int64) << shift) | (day - d0),
        (dst.astype(np.int64) << shift) | (day - d0),
    ])
    pair = np.unique(pair)                            # distinct (node, date) pairs
    active_days = np.bincount(pair >> shift, minlength=n).astype(np.int64)
    del pair
    print(f"[✓] active_days ({time.time()-t:.0f}s, day-field {shift} bits)", flush=True)

    # ── group 2: temporal frequency windows, anchored at ref = max incident ts
    t = time.time()
    ref = mx                                          # -1 where the node has no edges
    short_cut = ref - SW * DAY
    long_cut = ref - LW * DAY
    out_short = count_ge_threshold(src, ts, short_cut, n, out_deg)
    out_long = count_ge_threshold(src, ts, long_cut, n, out_deg)
    in_short = count_ge_threshold(dst, ts, short_cut, n, in_deg)
    in_long = count_ge_threshold(dst, ts, long_cut, n, in_deg)
    print(f"[✓] window counts ({time.time()-t:.0f}s)", flush=True)

    freq_out_short = out_short / SW
    freq_in_short = in_short / SW
    freq_out_long = out_long / LW
    freq_in_long = in_long / LW

    cols = dict(
        # ── Nhóm 1 — Basic Statistical (12) ──
        out_degree=out_deg,
        in_degree=in_deg,
        direction_ratio=np.round(out_deg / (out_deg + in_deg + 1e-9), 6),
        max_out_amount=np.round(max_out, 6),
        min_out_amount=np.round(min_out, 6),
        avg_out_amount=np.round(avg_out, 6),
        max_in_amount=np.round(max_in, 6),
        min_in_amount=np.round(min_in, 6),
        avg_in_amount=np.round(avg_in, 6),
        account_balance=np.round(balance, 6),
        lifetime_days=lifetime_days,
        active_days=active_days,
        # ── Nhóm 2 — Temporal Frequency (6) ──
        freq_out_short=np.round(freq_out_short, 6),
        freq_in_short=np.round(freq_in_short, 6),
        freq_out_long=np.round(freq_out_long, 6),
        freq_in_long=np.round(freq_in_long, 6),
        short_long_out_ratio=np.round(freq_out_short / (freq_out_long + 1e-9), 6),
        short_long_in_ratio=np.round(freq_in_short / (freq_in_long + 1e-9), 6),
    )

    np.savez(out_path, **cols)
    print(f"\n[✓] wrote {out_path}  ({out_path.stat().st_size/1e6:.0f} MB)  "
          f"total {time.time()-t0:.0f}s", flush=True)

    print("\n── summary (all 2,973,489 nodes) ──")
    for k, v in cols.items():
        v = np.asarray(v, dtype=np.float64)
        print(f"  {k:<22} mean={v.mean():>14.4f}  min={v.min():>12.4f}  max={v.max():>14.4f}")


if __name__ == "__main__":
    main()
